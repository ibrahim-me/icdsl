"""GDS / SPICE / JSON export."""
from __future__ import annotations

import klayout.db as kdb

from . import tech as T


def write_gds(top, lib, path):
    ly = kdb.Layout()
    ly.dbu = T.DBU_UM
    li = {k: ly.layer(*v) for k, v in T.GDS.items()}
    lbl = {k: ly.layer(*v) for k, v in T.GDS_LABEL.items()}
    pin = {k: ly.layer(*v) for k, v in T.GDS_PIN.items()}
    made = {}

    def make(L):
        if L.name in made:
            return made[L.name]
        if L.gds_path:                      # foreign block: copy its cell tree from the source GDS
            src = kdb.Layout()
            src.read(L.gds_path)
            sc = src.cell(L.gds_cell)
            c = ly.create_cell(L.name)
            c.copy_tree(sc)
            made[L.name] = c
            return c
        c = ly.create_cell(L.name)
        for s in L.shapes:
            r = s.rect
            c.shapes(li[s.layer]).insert(kdb.Box(r.x0, r.y0, r.x1, r.y1))
        for (net, d, s) in L.ports:
            r = s.rect
            c.shapes(pin[s.layer]).insert(kdb.Box(r.x0, r.y0, r.x1, r.y1))
            t = kdb.Text(net, kdb.Trans(r.cx, r.cy))
            c.shapes(pin[s.layer]).insert(t)
            c.shapes(lbl[s.layer]).insert(t)
        for (net, layer, x, y) in L.labels:
            c.shapes(lbl[layer]).insert(kdb.Text(net, kdb.Trans(x, y)))
        for ins in L.insts:
            cc = make(ins.cell)
            rot, mir = {"R0": (0, False), "MX": (0, True), "MY": (2, True), "R180": (2, False)}[ins.orient]
            c.insert(kdb.CellInstArray(cc.cell_index(), kdb.Trans(rot, mir, ins.x, ins.y)))
        made[L.name] = c
        return c

    make(top)
    ly.write(path)
    return path


def write_spice(top, path):
    with open(path, "w") as f:
        f.write(f"* reference netlist generated by icl for {top.name}\n")
        for (n, sc) in top.subckts:
            f.write(sc + "\n")
        f.write(top.spice)
        f.write(".end\n")
    return path
